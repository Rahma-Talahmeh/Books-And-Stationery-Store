CREATE OR REPLACE VIEW VW_TOP_RATED_BOOKS AS
SELECT p.PRODUCT_ID, p.TITLE, NVL(AVG(r.RATING), 0) AS AVERAGE_RATING, COUNT(r.REVIEW_ID) AS TOTAL_REVIEWS
FROM PRODUCTS p
LEFT JOIN REVIEWS r ON p.PRODUCT_ID = r.PRODUCT_ID
GROUP BY p.PRODUCT_ID, p.TITLE
ORDER BY AVERAGE_RATING DESC, TOTAL_REVIEWS DESC
FETCH FIRST 5 ROWS ONLY;

CREATE OR REPLACE VIEW VW_SALES_BY_CATEGORY AS
SELECT c.CATEGORY_NAME, NVL(SUM(oi.QUANTITY * oi.UNIT_PRICE), 0) AS TOTAL_SALES
FROM CATEGORIES c
LEFT JOIN PRODUCTS p ON c.CATEGORY_ID = p.CATEGORY_ID
LEFT JOIN ORDER_ITEMS oi ON p.PRODUCT_ID = oi.PRODUCT_ID
LEFT JOIN ORDERS o ON oi.ORDER_ID = o.ORDER_ID
WHERE o.ORDER_STATUS IS NULL OR o.ORDER_STATUS != 'Cancelled'
GROUP BY c.CATEGORY_NAME;