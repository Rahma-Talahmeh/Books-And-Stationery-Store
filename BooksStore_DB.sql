CREATE TABLE ADMINS (
    ADMIN_ID       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USERNAME       VARCHAR2(50) NOT NULL UNIQUE,
    PASSWORD_HASH  VARCHAR2(255) NOT NULL,
    FULL_NAME      VARCHAR2(100) NOT NULL,
    EMAIL          VARCHAR2(100) NOT NULL
);

CREATE TABLE CATEGORIES (
    CATEGORY_ID   NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CATEGORY_NAME VARCHAR2(100) NOT NULL UNIQUE,
    DESCRIPTION   VARCHAR2(500)
);

CREATE TABLE AUTHORS (
    AUTHOR_ID   NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    AUTHOR_NAME VARCHAR2(150) NOT NULL,
    BIO         VARCHAR2(1000)
);

CREATE TABLE PUBLISHERS (
    PUBLISHER_ID   NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PUBLISHER_NAME VARCHAR2(150) NOT NULL,
    CONTACT_EMAIL  VARCHAR2(100),
    PHONE          VARCHAR2(20)
);


CREATE TABLE PRODUCTS (
    PRODUCT_ID       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TITLE            VARCHAR2(200) NOT NULL,
    DESCRIPTION      VARCHAR2(2000),
    COVER_IMAGE      VARCHAR2(500),
    PRICE            NUMBER(10,2) NOT NULL,
    STOCK_QUANTITY   NUMBER DEFAULT 0 NOT NULL,
    ISBN             VARCHAR2(20),
    PUBLICATION_YEAR NUMBER(4),
    PRODUCT_TYPE     VARCHAR2(20) DEFAULT 'BOOK' CHECK (PRODUCT_TYPE IN ('BOOK', 'STATIONERY')),
    IS_FEATURED      NUMBER(1) DEFAULT 0 CHECK (IS_FEATURED IN (0, 1)),
    IS_NEW_ARRIVAL   NUMBER(1) DEFAULT 0 CHECK (IS_NEW_ARRIVAL IN (0, 1)),
    IS_BEST_SELLER   NUMBER(1) DEFAULT 0 CHECK (IS_BEST_SELLER IN (0, 1)),
    CATEGORY_ID      NUMBER NOT NULL,
    AUTHOR_ID        NUMBER,
    PUBLISHER_ID     NUMBER,
    CONSTRAINT FK_PROD_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORIES(CATEGORY_ID) ON DELETE CASCADE,
    CONSTRAINT FK_PROD_AUTHOR FOREIGN KEY (AUTHOR_ID) REFERENCES AUTHORS(AUTHOR_ID) ON DELETE SET NULL,
    CONSTRAINT FK_PROD_PUBLISHER FOREIGN KEY (PUBLISHER_ID) REFERENCES PUBLISHERS(PUBLISHER_ID) ON DELETE SET NULL
);

CREATE TABLE REVIEWS (
    REVIEW_ID     NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PRODUCT_ID    NUMBER NOT NULL,
    CUSTOMER_NAME VARCHAR2(100) NOT NULL,
    RATING        NUMBER(1) NOT NULL CHECK (RATING BETWEEN 1 AND 5),
    COMMENTS      VARCHAR2(1000),
    REVIEW_DATE   DATE DEFAULT SYSDATE,
    CONSTRAINT FK_REVIEW_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE
);


CREATE TABLE ORDERS (
    ORDER_ID         NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CUSTOMER_NAME    VARCHAR2(150) NOT NULL,
    PHONE_NUMBER     VARCHAR2(20) NOT NULL,
    DELIVERY_ADDRESS VARCHAR2(500) NOT NULL,
    ORDER_STATUS     VARCHAR2(30) DEFAULT 'Pending' CHECK (ORDER_STATUS IN ('Pending', 'Processing', 'Completed', 'Cancelled')),
    PAYMENT_METHOD   VARCHAR2(30) DEFAULT 'Cash on Delivery',
    TOTAL_AMOUNT     NUMBER(10,2) DEFAULT 0,
    ORDER_DATE       DATE DEFAULT SYSDATE
);

CREATE TABLE ORDER_ITEMS (
    ORDER_ITEM_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ORDER_ID      NUMBER NOT NULL,
    PRODUCT_ID    NUMBER NOT NULL,
    QUANTITY      NUMBER NOT NULL CHECK (QUANTITY > 0),
    UNIT_PRICE    NUMBER(10,2) NOT NULL,
    CONSTRAINT FK_ITEM_ORDER FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ORDER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_ITEM_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE
);


