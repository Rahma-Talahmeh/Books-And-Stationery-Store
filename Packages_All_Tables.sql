CREATE OR REPLACE PACKAGE BODY ADMIN_PACKAGE AS

    PROCEDURE GetAllAdmins AS
        c_all SYS_REFCURSOR;
    BEGIN
        OPEN c_all FOR 
        SELECT * FROM ADMINS;
        DBMS_SQL.RETURN_RESULT(c_all);
    END GetAllAdmins;

    PROCEDURE GETADMINBYID(ID IN NUMBER) AS
        C_ITEM SYS_REFCURSOR;
    BEGIN 
        OPEN C_ITEM FOR 
        SELECT * FROM ADMINS WHERE ADMIN_ID = ID;
        DBMS_SQL.RETURN_RESULT(C_ITEM);
    END GETADMINBYID;

    PROCEDURE CREATEADMIN(Username IN ADMINS.USERNAME%TYPE, Password_Hash IN ADMINS.PASSWORD_HASH%TYPE, Full_Name IN ADMINS.FULL_NAME%TYPE, Email IN ADMINS.EMAIL%TYPE) AS
    BEGIN
        INSERT INTO ADMINS VALUES(DEFAULT, Username, Password_Hash, Full_Name, Email);
        COMMIT;
    END CREATEADMIN;

    PROCEDURE UPDATEADMIN(ID IN NUMBER, Username IN ADMINS.USERNAME%TYPE, Password_Hash IN ADMINS.PASSWORD_HASH%TYPE, Full_Name IN ADMINS.FULL_NAME%TYPE, Email IN ADMINS.EMAIL%TYPE) AS
    BEGIN
        UPDATE ADMINS 
        SET USERNAME = Username, PASSWORD_HASH = Password_Hash, FULL_NAME = Full_Name, EMAIL = Email 
        WHERE ADMIN_ID = ID;
        COMMIT;
    END UPDATEADMIN;

    PROCEDURE DELETEADMIN(ID IN NUMBER) AS
    BEGIN
        DELETE FROM ADMINS WHERE ADMIN_ID = ID;
        COMMIT;
    END DELETEADMIN;

    PROCEDURE ADMIN_LOGIN(User_Name IN VARCHAR2, Pass IN VARCHAR2) AS
        c_all SYS_REFCURSOR;
    BEGIN
        OPEN c_all FOR
        SELECT ADMIN_ID, USERNAME, FULL_NAME, EMAIL
        FROM ADMINS
        WHERE USERNAME = User_Name AND PASSWORD_HASH = Pass;
        DBMS_SQL.RETURN_RESULT(c_all);
    END ADMIN_LOGIN;

END ADMIN_PACKAGE;
