
CREATE OR REPLACE PACKAGE ADMIN_PACKAGE AS
    PROCEDURE GetAllAdmins;
    PROCEDURE GETADMINBYID(ID IN NUMBER);
    PROCEDURE CREATEADMIN(Username IN ADMINS.USERNAME%TYPE, Password_Hash IN ADMINS.PASSWORD_HASH%TYPE, Full_Name IN ADMINS.FULL_NAME%TYPE, Email IN ADMINS.EMAIL%TYPE);
    PROCEDURE UPDATEADMIN(ID IN NUMBER, Username IN ADMINS.USERNAME%TYPE, Password_Hash IN ADMINS.PASSWORD_HASH%TYPE, Full_Name IN ADMINS.FULL_NAME%TYPE, Email IN ADMINS.EMAIL%TYPE);
    PROCEDURE DELETEADMIN(ID IN NUMBER);
    PROCEDURE ADMIN_LOGIN(User_Name IN VARCHAR2, Pass IN VARCHAR2);
